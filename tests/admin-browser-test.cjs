'use strict';
const assert=require('node:assert/strict');
const {chromium}=require('playwright');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const base=process.env.CD_TEST_BASE,token=process.env.CD_TEST_TOKEN;
 const errors=[];
 try{
  const page=await browser.newPage({viewport:{width:1920,height:1080}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(base+'?player=1#'+token);
  await page.locator('main h1').filter({hasText:'NTC 93'}).waitFor();
  assert.match(await page.locator('#status').innerText(),/Verbunden/);
  await page.locator('#next').click();
  await page.locator('main h1').filter({hasText:'HTTP-Test'}).waitFor();
  await page.locator('main img:not([hidden])').waitFor({state:'visible'});
  assert.match(await page.locator('main img').getAttribute('src'),/^blob:/);
  const imageBox=await page.locator('main img').boundingBox();assert.ok(imageBox&&imageBox.width>0&&imageBox.height>0);
  assert.equal(await page.locator('main script').count(),0);
  assert.match(await page.locator('main p').innerText(),/<script>example<\/script>/);
  const mainBox=await page.locator('main').boundingBox();const contentBox=await page.locator('.entry-layout').boundingBox();assert.ok(contentBox.y+contentBox.height<=mainBox.y+mainBox.height+1);
  await page.locator('#pause').click();
  assert.equal(await page.locator('#pause').getAttribute('aria-label'),'Play');
  await page.screenshot({path:'artifacts/managed-screen-desktop.png'});
  await page.setViewportSize({width:390,height:844});
  for(const selector of ['header','main','footer','.entry-layout']){const b=await page.locator(selector).boundingBox();assert.ok(b&&b.x>=-1&&b.x+b.width<=391,selector+' exceeds mobile viewport');}
  await page.screenshot({path:'artifacts/managed-screen-mobile.png'});
  const club=await browser.newPage({viewport:{width:1280,height:900}});
  club.on('pageerror',e=>errors.push(e.message));
  await club.goto(base+'?portal=club&verein=ntc93');
  await club.locator('input[name=password]').fill('test-club-password-123456');
  await club.getByRole('button',{name:'Anmelden',exact:true}).click();
  await club.getByRole('heading',{name:'Vereinsbackend'}).waitFor();
  await club.goto(base+'?portal=club&verein=ntc93&preview=1&club=ntc93&screen=hall');
  await club.locator('main h1').filter({hasText:'NTC 93'}).waitFor();
  assert.match(await club.locator('#status').innerText(),/VORSCHAU/);
  await club.locator('#next').click();
  await club.locator('main h1').filter({hasText:'HTTP-Test'}).waitFor();
  await club.locator('main img:not([hidden])').waitFor({state:'visible'});
  assert.match(await club.locator('main img').getAttribute('src'),/^blob:/);
  await club.screenshot({path:'artifacts/managed-preview.png'});
  // Edit a screen in the real admin form and verify its configured slide order and timing.
  const clubUrl=base+'?portal=club&verein=ntc93';
  await club.goto(clubUrl);
  const screen=club.locator('details.subpanel').filter({has:club.locator('input[name="slug"][value="hall"]')});
  await screen.locator(':scope > summary').click();
  await screen.locator('textarea[name=screen_welcome]').fill('Willkommen im Clubhaus');
  await screen.locator('input[name="module_rank[news]"]').fill('1');
  await screen.locator('input[name="module_rank[welcome]"]').fill('2');
  await screen.locator('input[name="module_dwell[news]"]').fill('5');
  await screen.getByRole('button',{name:'Bildschirm speichern',exact:true}).click();
  await club.getByText('Änderungen gespeichert.',{exact:true}).waitFor();
  await club.goto(clubUrl+'&preview=1&club=ntc93&screen=hall');
  await club.locator('main h1').filter({hasText:'HTTP-Test'}).waitFor();
  assert.match(await club.locator('#position').innerText(),/^1 \/ 2$/);
  await club.getByText('Willkommen im Clubhaus',{exact:true}).waitFor({timeout:10000});
  assert.match(await club.locator('#position').innerText(),/^2 \/ 2$/);
  await club.goto(clubUrl+'&preview=1&club=ntc93&screen=restaurant');
  await club.locator('main h1').filter({hasText:'NTC 93'}).waitFor();
  assert.equal(await club.locator('#position').innerText(),'1 / 1');
  assert.equal(await club.getByText('Willkommen im Clubhaus',{exact:true}).count(),0);
  // Responsive admin and member pages, independent of the large-screen display.
  const mobile=await browser.newPage({viewport:{width:390,height:844},isMobile:true,hasTouch:true});
  mobile.on('pageerror',e=>errors.push(e.message));
  const noOverflow=async()=>assert.ok(await mobile.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1),'page exceeds mobile viewport');
  await mobile.goto(clubUrl);
  await noOverflow();
  await mobile.locator('input[name=password]').fill('test-club-password-123456');
  await mobile.getByRole('button',{name:'Anmelden',exact:true}).click();
  await mobile.getByRole('heading',{name:'Vereinsbackend'}).waitFor();
  await noOverflow();
  const board=mobile.locator('details.subpanel').filter({has:mobile.locator('input[name="action"][value="partner-board"]')});
  await board.locator(':scope > summary').click();
  await board.locator('input[name=enabled]').check();
  await board.getByRole('button',{name:'Speichern',exact:true}).click();
  await mobile.getByText('Änderungen gespeichert.',{exact:true}).waitFor();
  await noOverflow();
  await mobile.screenshot({path:'artifacts/club-admin-mobile.png'});
  await mobile.goto(base+'?partner=submit&club=ntc93');
  await mobile.getByRole('heading',{name:'Spielpartner gesucht'}).waitFor();
  assert.equal(await mobile.locator('input[name=code]').count(),0);
  assert.equal(await mobile.locator('select[name=age_group] option').count(),4);
  await mobile.locator('select[name=age_group]').selectOption('child');
  assert.equal(await mobile.locator('input[name=guardian]').count(),1);
  assert.equal(await mobile.locator('input[name=email][required][type=email]').count(),1);
  assert.equal(await mobile.locator('input[name=phone]:not([required])').count(),1);
  assert.equal(await mobile.locator('select[name=lk] option').count(),6);
  for(const width of [360,390]){
    await mobile.setViewportSize({width,height:844});
    await noOverflow();
    const b=await mobile.locator('button.partner-submit').boundingBox();assert.ok(b&&b.height>=48&&b.x>=0&&b.x+b.width<=width+1);
  }
  await mobile.screenshot({path:'artifacts/partner-form-mobile.png',fullPage:true});
  await mobile.goto(base+'?partner=moderate&club=ntc93&decision=publish&token=invalid');
  await mobile.getByRole('heading',{name:'Spielpartnergesuch prüfen'}).waitFor();
  await noOverflow();
  await mobile.close();
  assert.deepEqual(errors,[]);
  console.log('Chromium: actual player, images, mobile, preview, safe text rendering, individual slide sequence, timing and audience isolation passed.');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exit(1);});
