'use strict';
// Exercise the actual countdown and pause functions from app.js with a controlled clock.
const assert=require('node:assert/strict');
const vm=require('node:vm');
const fs=require('node:fs');
const source=fs.readFileSync('public/assets/app.js','utf8');
const begin=source.indexOf('function infoControls(){');
const end=source.indexOf('function render(){',begin);
assert(begin>=0&&end>begin);
let now=100000;
const nodes=new Map();
const $=id=>{
  if(!nodes.has(id))nodes.set(id,{hidden:false,dataset:{},textContent:'',style:{setProperty(k,v){this[k]=v;}},setAttribute(k,v){this[k]=v;}});
  return nodes.get(id);
};
const ctx=vm.createContext({$,Date:{now:()=>now},tr:(de,en)=>de,t:()=>({info:'Informationsmodus'}),pilot:true,nightActive:false,nightLastInput:0,view:'info',slide:0,screens:['one','two','three'],dwell:12000,infoPauseLimit:25000,infoPaused:false,infoElapsed:0,infoPauseUntil:0,started:now,last:now,render(){vm.runInContext('infoControls()',ctx);}});
vm.runInContext(source.slice(begin,end),ctx);
const call=s=>vm.runInContext(s,ctx);
call('infoControls()');
assert.equal($('info-countdown').hidden,false);
assert.equal($('mode').textContent,'Informationsmodus');
assert.equal($('info-countdown').textContent,'Weiter in: 12 s');
now+=3000;call('toggleInfoPause()');
assert.equal($('info-countdown').textContent,'Pause: 25 s');
assert.equal($('info-toggle')['aria-pressed'],'true');
assert.equal($('mode').textContent,'Informationsmodus · angehalten');
now+=10000;call('tickInfo()');
assert.equal($('info-countdown').textContent,'Pause: 15 s');
assert.equal(ctx.slide,0);
call('infoInput()');
assert.equal(ctx.nightLastInput,now);
assert.equal($('info-countdown').textContent,'Pause: 25 s');
now+=24000;call('tickInfo()');
assert.equal($('info-countdown').textContent,'Pause: 1 s');
assert.equal(ctx.infoPaused,true);
now+=1000;call('tickInfo()');
assert.equal(ctx.infoPaused,false);
assert.equal($('info-countdown').textContent,'Weiter in: 9 s');
now+=9000;call('tickInfo()');
assert.equal(ctx.slide,1);
assert.equal($('info-countdown').textContent,'Weiter in: 12 s');
call('toggleInfoPause()');call('stepInfo(1)');
assert.equal(ctx.slide,2);assert.equal(ctx.infoPaused,true);
call('toggleInfoPause()');assert.equal(ctx.infoPaused,false);
ctx.view='home';call('infoControls()');assert.equal($('info-controls').hidden,true);
console.log('Info countdown tests OK');
