<?php
declare(strict_types=1);
// Install into the protected clubdisplay-admin directory. Host cron/SSH only.
if(PHP_SAPI!=='cli'){http_response_code(404);exit;}
if($argc!==2){fwrite(STDERR,"Usage: php backup-admin.php /absolute/private-backup-directory\n");exit(2);}
$source=__DIR__.'/clubdisplay-admin.sqlite';$out=realpath($argv[1]);$root=realpath(dirname(__DIR__));
if(!$out||!$root||!is_dir($out)||!is_writable($out)||$out===$root||str_starts_with($out,$root.DIRECTORY_SEPARATOR)||!is_file($source)||is_link($source)){
    fwrite(STDERR,"Invalid source or private destination. Use a directory outside the web root.\n");exit(2);
}
umask(0077);
$lock=fopen($out.'/.clubdisplay-backup.lock','c');
if(!$lock||!flock($lock,LOCK_EX|LOCK_NB)){fwrite(STDERR,"Backup already in progress.\n");exit(1);}
$status=0;$tmp=$out.'/clubdisplay-'.bin2hex(random_bytes(16)).'.tmp';
try{
    $db=new PDO('sqlite:'.$source,null,null,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION]);
    $db->exec('PRAGMA busy_timeout=5000');
    $db->exec('VACUUM INTO '.$db->quote($tmp));
    chmod($tmp,0600);
    $check=new PDO('sqlite:'.$tmp,null,null,[PDO::ATTR_ERRMODE=>PDO::ERRMODE_EXCEPTION]);
    if($check->query('PRAGMA integrity_check')->fetchColumn()!=='ok')throw new RuntimeException('Integrity check failed');
    $check=null;
    $dest=$out.'/clubdisplay-'.gmdate('Y-m-d-His').'-'.bin2hex(random_bytes(4)).'.sqlite';
    if(!rename($tmp,$dest))throw new RuntimeException('Rename failed');
    // Retention: only backups generated by this script, never unrelated files.
    foreach(glob($out.'/clubdisplay-*.sqlite')?:[] as $file)if(!is_link($file)&&preg_match('/^clubdisplay-\d{4}-\d{2}-\d{2}-\d{6}-[a-f0-9]{8}\.sqlite$/D',basename($file))&&filemtime($file)<time()-30*86400)unlink($file);
    echo "Backup created; SQLite integrity check OK.\n";
}catch(Throwable $e){fwrite(STDERR,"Backup failed.\n");$status=1;}
finally{if(is_file($tmp))@unlink($tmp);flock($lock,LOCK_UN);fclose($lock);}
exit($status);
